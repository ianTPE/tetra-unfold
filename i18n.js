// 語言的選擇順序：網址 ?lang= → 上次選的 → 瀏覽器語言 → 英文
function pickLang() {
  const ok = l => l && Object.prototype.hasOwnProperty.call(LANGS, l);
  const fromTag = tag => {
    const t = String(tag || '').toLowerCase();
    if (/^zh-(tw|hk|mo|hant)/.test(t)) return 'zh-Hant';
    if (t.startsWith('zh')) return 'zh-Hans';
    const base = t.split('-')[0];
    return ok(base) ? base : null;
  };
  const param = new URLSearchParams(location.search).get('lang');
  if (ok(param)) return param;
  if (fromTag(param)) return fromTag(param);
  try { const saved = localStorage.getItem('tetra-unfold-lang'); if (ok(saved)) return saved; } catch (e) { /* 不能用就跳過 */ }
  for (const tag of navigator.languages || [navigator.language]) { const l = fromTag(tag); if (l) return l; }
  return 'en';
}
